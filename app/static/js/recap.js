/* AI recap review modal. Uses globals from meeting.js ($, M, PEOPLE, load, patchMeeting). */
let DRAFT = null;

$("gen-recap").addEventListener("click", async e => {
  const notes = $("raw-notes").value;
  await withSpinner(e.currentTarget, async () => {
    try {
      await api("PATCH", `/api/meetings/${MEETING_ID}`, { raw_notes: notes });   // keep stored notes in sync
      DRAFT = await api("POST", `/api/meetings/${MEETING_ID}/recap`, { raw_notes: notes });
      renderRecap(); new bootstrap.Modal("#recapModal").show();
    } catch (_) {}
  });
});

function renderRecap() {
  const d = DRAFT;
  const banner = d.warning ? `<div class="alert alert-warning"><i class="bi bi-exclamation-triangle"></i> ${esc(d.warning)}</div>`
    : `<div class="alert alert-info py-2"><i class="bi bi-stars"></i> Generated by AI. Please review before saving.</div>`;
  const rows = d.items.map((i, k) => `<tr class="${i.possible_duplicate_of ? "table-warning" : ""}">
    <td><input type="checkbox" class="form-check-input rc-on" ${i.possible_duplicate_of ? "" : "checked"}></td>
    <td><input class="form-control form-control-sm rc-title" value="${esc(i.title).replace(/"/g, "&quot;")}">
      <div class="small text-muted mt-1" title="Evidence from notes">“${esc(i.evidence)}”</div>
      ${i.needs_review ? `<span class="badge text-bg-warning">⚠ needs review</span>` : ""}
      ${i.possible_duplicate_of ? `<span class="badge text-bg-danger" title="${esc(i.possible_duplicate_of.title)}">possible duplicate of “${esc(i.possible_duplicate_of.title)}”</span>` : ""}</td>
    <td><select class="form-select form-select-sm rc-owner">${personOptions(PEOPLE, i.owner_id || "")}</select></td>
    <td><input type="date" class="form-control form-control-sm rc-due" value="${i.due_date || ""}"></td>
    <td><select class="form-select form-select-sm rc-prio">${["low", "medium", "high"].map(p => `<option ${p === i.priority ? "selected" : ""}>${p}</option>`).join("")}</select></td></tr>`).join("");
  $("recap-body").innerHTML = `${banner}
    <label class="form-label fw-semibold">Summary</label><textarea id="rc-summary" class="form-control mb-3" rows="3">${esc(d.summary)}</textarea>
    <label class="form-label fw-semibold">Decisions <span class="text-muted small">(one per line)</span></label>
    <textarea id="rc-decisions" class="form-control mb-3" rows="3">${esc(d.decisions.join("\n"))}</textarea>
    ${d.open_questions.length ? `<div class="mb-3"><strong>Open questions</strong><ul>${d.open_questions.map(q => `<li>${esc(q)}</li>`).join("")}</ul></div>` : ""}
    <label class="form-label fw-semibold">Action items (${d.items.length})</label>
    <div class="table-responsive"><table class="table table-sm align-middle"><thead><tr><th>Add</th><th>Title</th><th>Owner</th><th>Due</th><th>Priority</th></tr></thead>
      <tbody>${rows || `<tr><td colspan="5" class="text-muted">No action items found.</td></tr>`}</tbody></table></div>`;
}

$("recap-apply").addEventListener("click", async e => {
  const trs = [...document.querySelectorAll("#recap-body tbody tr")].filter(tr => tr.querySelector(".rc-on"));
  const items = trs.filter(tr => tr.querySelector(".rc-on").checked).map((tr, _) => {
    const k = trs.indexOf(tr), src = DRAFT.items[k];
    return { title: tr.querySelector(".rc-title").value, owner_id: tr.querySelector(".rc-owner").value || null,
      due_date: tr.querySelector(".rc-due").value || null, priority: tr.querySelector(".rc-prio").value,
      evidence: src.evidence, needs_review: src.needs_review && !tr.querySelector(".rc-owner").value ? true : src.needs_review };
  });
  await withSpinner(e.currentTarget, async () => {
    try {
      const r = await api("POST", `/api/meetings/${MEETING_ID}/recap/apply`, {
        summary: $("rc-summary").value, decisions: $("rc-decisions").value.split("\n").map(s => s.trim()).filter(Boolean), items, source: DRAFT.source });
      bootstrap.Modal.getInstance($("recapModal")).hide();
      toast(`Recap saved. ${r.created_items.length} action item(s) added.`); await load();
    } catch (_) {}
  });
});
